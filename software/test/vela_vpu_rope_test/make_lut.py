"""RoPE unit LUT generator (CustomRoPEUnit.scala).

Writes
  lutA.hex, lutB.hex (this directory)      reference copies (one entry per line)
  src/main/scala/velaVPU/exu/RoPELutData.scala
                                           the ROM contents the RTL is built from (elaboration reads this object)

The RTL takes the table from RoPELutData.scala, so a new table only needs this script + a new bitstream.
Because the table is a .scala file, chipyard's make sees the change and re-elaborates (a .hex change alone
would not be noticed and the old table would stay in the bitstream).

usage: python3 make_lut.py [--base B]     (needs numpy; default base 500000 = Llama 3 / BitNet b1.58 2B-4T)
"""
import argparse
import os
import struct

import numpy as np

# RoPE parameters (fixed by the RTL: 64 x 64 entries per ROM, head size 128)
D_MODEL = 128		# d = 128
Q_SIZE  = 64		# q = m / 64
R_SIZE  = 64		# r = m % 64
I_SIZE  = 64		# i = (idx % 128) / 2
BASE    = 500000.0	# rope freq_base of the target model (was 10000.0 until 2026-11)

HERE = os.path.dirname(os.path.abspath(__file__))
SCALA_OUT = os.path.join(HERE, "..", "..", "..", "src", "main", "scala", "velaVPU", "exu", "RoPELutData.scala")

def f16(x):
    """float -> FP16 bit pattern"""
    return struct.unpack('<H', struct.pack('<e', np.float16(x)))[0]

def q1p7(x):
    """float -> signed Q1.7 (2's complement, uint8)"""
    x = np.clip(x, -1.0, 0.9921875)
    q = int(round(x * 128))
    return q & 0xFF

def make(base):
    theta = [base ** (-2.0 * i / D_MODEL) for i in range(I_SIZE)]
    lutA = []
    lutB = []
    # LUT A: base angle (q-major), FP16 {sin, cos}
    for q in range(Q_SIZE):
        for i in range(I_SIZE):
            phase = (q * 64.0) * theta[i]
            cosA = f16(np.cos(phase))
            sinA = f16(np.sin(phase))
            lutA.append(f"{(sinA << 16 | cosA):08x}")
    # LUT B: m scaling (r-major), Q1.7 {sin, cos}
    for r in range(R_SIZE):
        for i in range(I_SIZE):
            phase = float(r) * theta[i]
            cosB = q1p7(np.cos(phase))
            sinB = q1p7(np.sin(phase))
            lutB.append(f"{(sinB << 8 | cosB):04x}")
    return lutA, lutB

def scala_source(base, lutA, lutB):
    def rows(entries):   # one ROM row (64 entries) per line
        return " +\n".join(f'    "{"".join(entries[k:k + 64])}"' for k in range(0, len(entries), 64))
    return f'''// Generated by software/test/vela_vpu_rope_test/make_lut.py (base {base:g}). Do not edit: change BASE there and rerun.
package velaVPU.exu

// ROM contents of RoPEUnit (CustomRoPEUnit.scala), 4096 entries each, address = row * 64 + i:
//   A: row q = m / 64, {{sin, cos}}(64 q * theta_i) as FP16, 32 bit {{sin[31:16], cos[15:0]}}
//   B: row r = m % 64, {{sin, cos}}(r * theta_i) as Q1.7,      16 bit {{sin[15:8],  cos[7:0]}}
//   theta_i = base^(-2i/{D_MODEL})
object RoPELutData {{
  val base: Double = {base!r}
  val headDim: Int = {D_MODEL}

  def lutA: Seq[BigInt] = parse(lutAHex, 8)
  def lutB: Seq[BigInt] = parse(lutBHex, 4)

  private def parse(s: String, digits: Int): Seq[BigInt] = s.grouped(digits).map(BigInt(_, 16)).toSeq

  private val lutAHex: String =
{rows(lutA)}

  private val lutBHex: String =
{rows(lutB)}
}}
'''

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", type=float, default=BASE, help=f"RoPE base (default {BASE:g})")
    args = ap.parse_args()

    lutA, lutB = make(args.base)
    outputs = [(os.path.join(HERE, "lutA.hex"), "\n".join(lutA) + "\n"),
               (os.path.join(HERE, "lutB.hex"), "\n".join(lutB) + "\n"),
               (SCALA_OUT, scala_source(args.base, lutA, lutB))]
    for path, text in outputs:
        # write only on change: a rewritten .scala file makes chipyard rebuild and re-elaborate
        if os.path.exists(path) and open(path).read() == text:
            print(f"base {args.base:g}: {os.path.relpath(path)} unchanged")
            continue
        with open(path, "w") as f:
            f.write(text)
        print(f"base {args.base:g}: wrote {os.path.relpath(path)}")

if __name__ == "__main__":
    main()
